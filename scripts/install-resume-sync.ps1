<#
  Installs the resume sync so it runs for every logon, and starts it now.

    powershell -ExecutionPolicy Bypass -File scripts\install-resume-sync.ps1

  No elevation: this drops a hidden launcher in the current user's Startup folder
  (Task Scheduler registration is refused without admin on this machine). Remove it
  by deleting the two files the script prints, and ending the powershell.exe process.
#>
param(
  [string]$Source = 'C:\GT\Resumes\Model\Summer27\Juno\Akash_Sarode.pdf',
  [switch]$NoStart
)

$ErrorActionPreference = 'Stop'

$watch   = Join-Path $PSScriptRoot 'watch-resume.ps1'
$startup = Join-Path $env:APPDATA 'Microsoft\Windows\Start Menu\Programs\Startup'
$vbs     = Join-Path $startup 'catan-portfolio-resume-sync.vbs'

# A .vbs launcher rather than a .lnk, so the powershell window never flashes on logon.
$cmd = 'powershell.exe -NoProfile -NonInteractive -ExecutionPolicy Bypass -WindowStyle Hidden -File "{0}" -Source "{1}"' -f $watch, $Source

# .Replace(), not the -replace operator: inline `-replace '"', '""'` inside a concatenation
# binds so that the comma wins, and the one Run statement gets written out as three lines.
$quoted = $cmd.Replace('"', '""')
$line   = 'CreateObject("WScript.Shell").Run "' + $quoted + '", 0, False'

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("' Starts the Catan portfolio resume sync watcher, hidden, at logon.")
$lines.Add("' Generated by scripts\install-resume-sync.ps1 - delete this file to uninstall.")
$lines.Add($line)
if ($lines.Count -ne 3) { throw 'launcher build produced the wrong shape' }
Set-Content -Path $vbs -Value $lines -Encoding ascii

Write-Output "Installed launcher: $vbs"
Write-Output "Watching:           $Source"
Write-Output "Log:                $(Join-Path $env:LOCALAPPDATA 'catan-portfolio\resume-sync.log')"

if (-not $NoStart) {
  Start-Process -FilePath 'wscript.exe' -ArgumentList ('"{0}"' -f $vbs) -WindowStyle Hidden
  Write-Output 'Started it for this session too.'
}
